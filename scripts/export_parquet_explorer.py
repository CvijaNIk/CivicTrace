"""Rebuild only the reviewed invented fixture through existing importer and snapshot writer."""

import argparse
import hashlib
import json
import subprocess
import sys
import tempfile
from pathlib import Path

from civictrace.parquet_explorer import export_snapshot
from civictrace.snapshots import verify_snapshot

ROOT = Path(__file__).resolve().parents[1]
TARGET = ROOT / "frontend/public/data/parquet-v1.json"


def export():
    with tempfile.TemporaryDirectory() as tmp:
        directory = Path(tmp) / "invented"
        subprocess.run(
            [
                sys.executable,
                str(ROOT / "scripts/snapshot_example.py"),
                str(directory),
                "--rows",
                "4",
                "--preview-fixture",
            ],
            check=True,
            capture_output=True,
        )
        snapshot = directory / "snapshot-a"
        # Trust is limited to the fixture just generated by this reviewed source code.
        pin = verify_snapshot(snapshot)["snapshot_id"]
        return export_snapshot(snapshot, expected_snapshot_id=pin)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    raw = export()
    if args.check:
        committed = json.loads(TARGET.read_text())
        rebuilt = json.loads(raw)
        # Verification-time Python/runtime versions can differ across the CI matrix.
        # Snapshot identity, writer version, implementation hashes and every row must match.
        committed["lineage"].pop("environment")
        rebuilt["lineage"].pop("environment")
        if committed != rebuilt:
            raise SystemExit("Preview differs: review fixture, writer or implementation changes")
        pin = json.loads((ROOT / "frontend/src/parquet-pin.json").read_text())
        if pin != dict(
            snapshot_id=rebuilt["snapshot_id"],
            sha256=hashlib.sha256(TARGET.read_bytes()).hexdigest(),
        ):
            raise SystemExit("Committed preview checksum pin differs")
    else:
        TARGET.write_text(raw)
        pin = dict(
            snapshot_id=json.loads(raw)["snapshot_id"],
            sha256=hashlib.sha256(raw.encode()).hexdigest(),
        )
        (ROOT / "frontend/src/parquet-pin.json").write_text(json.dumps(pin, indent=2) + "\n")


if __name__ == "__main__":
    main()
